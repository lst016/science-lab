// 上海版专属变体在 sh-variants-*.ts 登记，模型分支在 src/sim/sh-*.ts。
for (const def of Object.values(SH_VARIANTS)) MODELED_SCENE_VARIANTS.add(def.variant);

export function getSimulationCoverage() {
  const variants = [...new Set(experiments.map((e) => e.sceneVariant))].sort();
  const unregistered = variants.filter((variant) => !MODELED_SCENE_VARIANTS.has(variant));
  const byFamily = Object.fromEntries([...new Set(experiments.map((e) => e.family))].sort().map((family) => [family, experiments.filter((e) => e.family === family).length]));
  return { experimentCount: experiments.length, variantCount: variants.length, registeredVariantCount: variants.length - unregistered.length, unregisteredVariants: unregistered, byFamily, note: '登记仅表示存在对应模拟分支；不代表每个分支都提供定量模型。请结合每条 Observation.fidelity 和 warnings 判断。' };
}
